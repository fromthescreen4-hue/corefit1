export function searchFoods(query, filterCategory = 'All', filterDiet = 'all') {
  const cleanQ = (query || '').toLowerCase().trim();
  return FOOD_DATABASE.filter(f => {
    // Diet filter
    if (filterDiet !== 'all') {
      if (filterDiet === 'veg' && f.diet !== 'veg' && f.diet !== 'vegan') return false;
      if (filterDiet === 'vegan' && f.diet !== 'vegan') return false;
      if (filterDiet === 'non_veg' && f.diet !== 'non_veg') return false;
    }
    // Category filter
    if (filterCategory !== 'All') {
      if (filterCategory === 'South Indian' && f.category !== 'South Indian') return false;
      if (filterCategory === 'Wider Indian' && f.category !== 'Wider Indian') return false;
      if (filterCategory === 'Wider Asian' && f.category !== 'Wider Asian') return false;
      if (filterCategory === 'High Protein' && (f.protein || 0) < 12) return false;
    }
    if (!cleanQ) return true;
    const matchesName = f.name.toLowerCase().includes(cleanQ);
    const matchesAliases = f.aliases && f.aliases.some(a => a.toLowerCase().includes(cleanQ));
    return matchesName || matchesAliases;
  });
}
